"""Write SKSE_Source/include/CorpsePatchHashes.h from the built SexLab 1.66 corpse patch pex files.

A pex embeds its compile time, so every recompile changes the hashes: run this after each
`compile: pyro (SexLab 1.66 patch)` and rebuild the DLL. --check fails when the header is stale.
"""
import argparse
import hashlib
import pathlib
import sys

FILES = ["sslActorAlias.pex", "sslActorLibrary.pex"]


def render(pex_dir: pathlib.Path) -> str:
    rows = []
    for name in FILES:
        digest = hashlib.sha256((pex_dir / name).read_bytes()).hexdigest()
        rows.append('        PexHash{"%s", "%s"},' % (name, digest))
    body = "\n".join(rows)
    return (
        "#pragma once\n"
        "// Generated by python_scripts/corpse-patch-hashes.py from patch_sexlab166/Scripts. Do not edit.\n"
        "#include <array>\n"
        "#include <string_view>\n\n"
        "namespace CorpsePatch\n"
        "{\n"
        "    struct PexHash\n"
        "    {\n"
        "        std::string_view file;\n"
        "        std::string_view sha256;\n"
        "    };\n\n"
        f"    inline constexpr std::array<PexHash, {len(FILES)}> kPexHashes{{\n"
        f"{body}\n"
        "    };\n"
        "}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("-p", "--pex-dir", default="patch_sexlab166/Scripts")
    ap.add_argument("-o", "--out", default="SKSE_Source/include/CorpsePatchHashes.h")
    ap.add_argument("--check", action="store_true", help="fail if the header does not match the pex files")
    args = ap.parse_args()
    text = render(pathlib.Path(args.pex_dir))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out} is stale: run make corpse-patch and rebuild the DLL", file=sys.stderr)
            return 1
        print(f"{out} matches {args.pex_dir}")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
